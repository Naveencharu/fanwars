CREATE OR REPLACE FUNCTION public.create_fanwar(p_title text, p_description text, p_category text, p_tribe_id bigint, p_option_a text, p_option_b text)
 RETURNS bigint
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'public'
AS $function$
DECLARE
    v_user_id uuid;
    v_battle_id bigint;
BEGIN
    v_user_id := auth.uid();

    IF v_user_id IS NULL THEN
        RAISE EXCEPTION 'Not authenticated';
    END IF;

    IF trim(coalesce(p_title, '')) = '' THEN
        RAISE EXCEPTION 'FanWar title is required';
    END IF;

    IF trim(coalesce(p_option_a, '')) = '' THEN
        RAISE EXCEPTION 'Option A is required';
    END IF;

    IF trim(coalesce(p_option_b, '')) = '' THEN
        RAISE EXCEPTION 'Option B is required';
    END IF;

    IF p_option_a = p_option_b THEN
        RAISE EXCEPTION 'FanWar options must be different';
    END IF;

    IF NOT EXISTS (
        SELECT 1
        FROM public.tribes
        WHERE id = p_tribe_id
    ) THEN
        RAISE EXCEPTION 'Invalid Tribe';
    END IF;

    INSERT INTO public.battles (
        title,
        description,
        category,
        status,
        tribe_id,
        created_by
    )
    VALUES (
        trim(p_title),
        nullif(trim(p_description), ''),
        trim(p_category),
        'pending',
        p_tribe_id,
        v_user_id
    )
    RETURNING id INTO v_battle_id;

    INSERT INTO public.battle_options (
        battle_id,
        name,
        position
    )
    VALUES
        (v_battle_id, trim(p_option_a), 1),
        (v_battle_id, trim(p_option_b), 2);

    RETURN v_battle_id;
END;
$function$;

ALTER FUNCTION "public"."create_fanwar"(p_title text, p_description text, p_category text, p_tribe_id bigint, p_option_a text, p_option_b text) OWNER TO "postgres";

CREATE OR REPLACE FUNCTION public.get_battle_creator(p_battle_id bigint)
 RETURNS TABLE(handler text, display_name text)
 LANGUAGE sql

CREATE OR REPLACE FUNCTION public.get_or_create_tribe(p_name text)
 RETURNS bigint
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'public'
AS $function$
declare
    v_name text;
    v_tribe_id bigint;

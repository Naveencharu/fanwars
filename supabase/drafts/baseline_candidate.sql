CREATE OR REPLACE FUNCTION public.claim_referral(p_referral_handler text, p_source_type text DEFAULT NULL::text, p_source_id bigint DEFAULT NULL::bigint)
 RETURNS bigint
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'public'
AS $function$
declare
    v_user_id uuid;
    v_referrer_id uuid;
    v_referral_id bigint;
begin
    v_user_id := auth.uid();

    if v_user_id is null then
        raise exception 'Not authenticated';
    end if;

    if trim(coalesce(p_referral_handler, '')) = '' then
        raise exception 'Referral handler is required';
    end if;

    select id
    into v_referrer_id
    from public.profiles
    where lower(handler) = lower(trim(replace(p_referral_handler, '@', '')))
    limit 1;

    if v_referrer_id is null then
        raise exception 'Referral handler not found';
    end if;

    if v_referrer_id = v_user_id then
        raise exception 'You cannot refer yourself';
    end if;

    insert into public.fan_referrals (
        referrer_user_id,
        referred_user_id,
        referral_handler,
        source_type,
        source_id
    )
    values (
        v_referrer_id,
        v_user_id,
        lower(trim(replace(p_referral_handler, '@', ''))),
        nullif(trim(p_source_type), ''),
        p_source_id
    )
    on conflict (referred_user_id) do nothing
    returning id into v_referral_id;

    return v_referral_id;
end;
$function$;


CREATE OR REPLACE FUNCTION public.join_clan(p_clan_id bigint)
 RETURNS void
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'public'
AS $function$
declare
    v_user_id uuid;
    v_tribe_id bigint;
begin

    v_user_id := auth.uid();

    if v_user_id is null then
        raise exception 'Not authenticated';
    end if;


    select tribe_id
    into v_tribe_id
    from public.clans
    where id = p_clan_id
    and status = 'active';


    if v_tribe_id is null then
        raise exception 'Clan not found';
    end if;


    -- Must belong to parent Tribe

    if not exists (
        select 1
        from public.tribe_members
        where tribe_id = v_tribe_id
        and user_id = v_user_id
    ) then
        raise exception 'Join the Tribe before joining this Clan';
    end if;


    insert into public.clan_members (
        clan_id,
        user_id,
        role
    )
    values (
        p_clan_id,
        v_user_id,
        'member'
    )
    on conflict (clan_id, user_id)
    do nothing;

end;
$function$;


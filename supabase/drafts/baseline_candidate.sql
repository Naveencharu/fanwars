CREATE OR REPLACE FUNCTION public.create_clan(p_tribe_id bigint, p_name text, p_description text DEFAULT NULL::text)
 RETURNS bigint
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'public'
AS $function$
declare
    v_user_id uuid;
    v_name text;
    v_description text;
    v_clan_id bigint;
begin

    v_user_id := auth.uid();

    if v_user_id is null then
        raise exception 'Not authenticated';
    end if;


    -- Normalize name

    v_name := trim(p_name);

    if v_name = '' then
        raise exception 'Clan name is required';
    end if;

    if char_length(v_name) < 2 then
        raise exception 'Clan name must contain at least 2 characters';
    end if;

    if char_length(v_name) > 80 then
        raise exception 'Clan name must not exceed 80 characters';
    end if;


    -- Normalize description

    v_description := nullif(trim(coalesce(p_description, '')), '');

    if v_description is not null
       and char_length(v_description) > 500 then

        raise exception 'Clan description must not exceed 500 characters';

    end if;


    -- Tribe must exist

    if not exists (
        select 1
        from public.tribes
        where id = p_tribe_id
    ) then
        raise exception 'Tribe not found';
    end if;


    -- IMPORTANT:
    -- User must belong to the Tribe before creating a Clan.

    if not exists (
        select 1
        from public.tribe_members
        where tribe_id = p_tribe_id
        and user_id = v_user_id
    ) then
        raise exception 'Join this Tribe before creating a Clan';
    end if;


    -- Prevent duplicate Clan names inside same Tribe

    if exists (
        select 1
        from public.clans
        where tribe_id = p_tribe_id
        and lower(trim(name)) = lower(v_name)
    ) then
        raise exception 'A Clan with this name already exists in this Tribe';
    end if;


    -- Create Clan

    insert into public.clans (
        tribe_id,
        name,
        description,
        created_by
    )
    values (
        p_tribe_id,
        v_name,
        v_description,
        v_user_id
    )
    returning id into v_clan_id;


    -- Creator automatically becomes Captain

    insert into public.clan_members (
        clan_id,
        user_id,
        role
    )
    values (
        v_clan_id,
        v_user_id,
        'captain'
    );


    return v_clan_id;

exception

    when unique_violation then
        raise exception
            'A Clan with this name already exists in this Tribe';

end;
$function$;


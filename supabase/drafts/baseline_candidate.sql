    if auth.uid() is null then
        raise exception 'Not authenticated';
    end if;

    v_name := trim(p_name);

    if v_name = '' then
        raise exception 'Tribe name is required';
    end if;

    if length(v_name) > 100 then
        raise exception 'Tribe name is too long';
    end if;

    select id
    into v_tribe_id
    from public.tribes
    where lower(trim(name)) = lower(v_name)
    limit 1;

    if v_tribe_id is not null then
        return v_tribe_id;
    end if;

    insert into public.tribes (name)
    values (v_name)
    returning id into v_tribe_id;

    return v_tribe_id;

exception
    when unique_violation then
        select id
        into v_tribe_id
        from public.tribes
        where lower(trim(name)) = lower(v_name)
        limit 1;

        return v_tribe_id;
end;
$function$;


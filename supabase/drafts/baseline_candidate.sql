CREATE OR REPLACE FUNCTION public.set_fanwar_clans(p_battle_id bigint, p_clan_a_id bigint, p_clan_b_id bigint)
 RETURNS void
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'public'
AS $function$
declare
    v_user_id uuid;
    v_created_by uuid;
    v_tribe_a bigint;
    v_tribe_b bigint;
    v_option_ids bigint[];
begin
    v_user_id := auth.uid();

    if v_user_id is null then
        raise exception 'Authentication required.';
    end if;

    if p_clan_a_id = p_clan_b_id then
        raise exception 'A Clan cannot battle itself.';
    end if;

    select created_by
    into v_created_by
    from public.battles
    where id = p_battle_id;

    if v_created_by is null then
        raise exception 'FanWar not found.';
    end if;

    if v_created_by <> v_user_id then
        raise exception 'You can only configure your own FanWar.';
    end if;

    select tribe_id
    into v_tribe_a
    from public.clans
    where id = p_clan_a_id
      and status = 'active';

    select tribe_id
    into v_tribe_b
    from public.clans
    where id = p_clan_b_id
      and status = 'active';

    if v_tribe_a is null or v_tribe_b is null then
        raise exception 'One or both Clans are unavailable.';
    end if;

    if v_tribe_a <> v_tribe_b then
        raise exception 'Clan FanWars currently require both Clans to belong to the same Tribe.';
    end if;

    if not exists (
        select 1
        from public.clan_members
        where clan_id = p_clan_a_id
          and user_id = v_user_id
          and role = 'captain'
    ) then
        raise exception 'Only the Captain of Clan A can create this Clan FanWar.';
    end if;

    select array_agg(id order by id)
    into v_option_ids
    from public.battle_options
    where battle_id = p_battle_id;

    if coalesce(array_length(v_option_ids, 1), 0) <> 2 then
        raise exception 'Clan FanWars require exactly two battle options.';
    end if;

    update public.battle_options
    set clan_id = p_clan_a_id
    where id = v_option_ids[1];

    update public.battle_options
    set clan_id = p_clan_b_id
    where id = v_option_ids[2];
end;
$function$;

ALTER FUNCTION "public"."set_fanwar_clans"(p_battle_id bigint, p_clan_a_id bigint, p_clan_b_id bigint) OWNER TO "postgres";


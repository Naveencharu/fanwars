CREATE OR REPLACE FUNCTION public.leave_clan(p_clan_id bigint)
 RETURNS void
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'public'
AS $function$
declare
    v_user_id uuid;
    v_role text;
begin

    v_user_id := auth.uid();

    if v_user_id is null then
        raise exception 'Not authenticated';
    end if;


    select role
    into v_role
    from public.clan_members
    where clan_id = p_clan_id
    and user_id = v_user_id;


    if v_role is null then
        return;
    end if;


    -- V1 protection:
    -- Captain cannot accidentally abandon their Clan.


CREATE OR REPLACE FUNCTION public.cast_vote(p_battle_id bigint, p_option_id bigint)
 RETURNS TABLE(vote_id bigint, selected_option_id bigint)
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'public'
AS $function$
declare
    v_user_id uuid;
    v_vote_id bigint;
begin

    -- Get authenticated user
    v_user_id := auth.uid();

    if v_user_id is null then
        raise exception 'Not authenticated';
    end if;


    -- Battle must exist and be live
    if not exists (
        select 1
        from public.battles
        where id = p_battle_id
          and status = 'live'
    ) then
        raise exception 'Battle is not live';
    end if;


    -- Option must belong to this battle
    if not exists (
        select 1
        from public.battle_options
        where id = p_option_id
          and battle_id = p_battle_id
    ) then
        raise exception 'Invalid battle option';
    end if;


    -- One user = one vote per battle
    insert into public.votes (
        battle_id,
        option_id,
        user_id
    )
    values (
        p_battle_id,
        p_option_id,
        v_user_id
    )
    on conflict (battle_id, user_id)
    do nothing
    returning id into v_vote_id;


    -- Already voted
    if v_vote_id is null then
        raise exception 'You have already voted in this FanWar';
    end if;


    return query
    select
        v_vote_id,
        p_option_id;

end;
$function$;


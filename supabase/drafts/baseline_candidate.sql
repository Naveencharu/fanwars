CREATE OR REPLACE FUNCTION public.get_battle_results(p_battle_id bigint)
 RETURNS TABLE(option_id bigint, option_name text, vote_count bigint)
 LANGUAGE sql
 STABLE SECURITY DEFINER
 SET search_path TO 'public'
AS $function$
    select
        o.id as option_id,
        o.name as option_name,
        count(v.id)::bigint as vote_count
    from public.battle_options o
    left join public.votes v
        on v.option_id = o.id
       and v.battle_id = p_battle_id
    where o.battle_id = p_battle_id
    group by
        o.id,
        o.name,
        o.position
    order by
        o.position;
$function$;

